#!/usr/bin/env python3
"""Export the built curriculum pack to a JS module for the vanilla frontend.

Run:  python scripts/export_curriculum.py
Reads packs/pack_class9_science_or_v1-1.0.0.json and writes
frontend/src/curriculum.js with concepts, chunks, questions and glossary
using the SAME ids the backend uses (c0001…, q_…, ch001…).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = json.loads((ROOT / "packs" / "pack_class9_science_or_v1-1.0.0.json").read_text(encoding="utf-8"))
OUT = ROOT / "frontend" / "src" / "curriculum.js"

DIFF = {"easy": 1, "medium": 2, "hard": 3}
manifest = PACK["manifest"]

concepts = []
for i, c in enumerate(PACK["concepts"]):
    chunks = sorted([k for k in PACK["chunks"] if k["concept_id"] == c["concept_id"]], key=lambda k: k["ordinal"])
    sents = []
    for k in chunks[:1]:
        sents = [s.strip() for s in re.split(r"(?<=।)", k["text_or"]) if s.strip()]
    ex = chunks[1]["text_or"] if len(chunks) > 1 else c.get("summary_or", "")
    concepts.append({
        "id": c["concept_id"],
        "ch": c["chapter_id"],
        "pre": c.get("prerequisites") or [],
        "t": {"en": c["title_en"], "or": c["title_or"]},
        "s": sents,
        "ex": ex,
        "src": (c.get("source_refs") or [""])[0],
    })

# concept membership for glossary terms (term appears in the concept's chunk text)
texts = {c["concept_id"]: " ".join(k["text_or"] for k in PACK["chunks"] if k["concept_id"] == c["concept_id"]) for c in PACK["concepts"]}
glossary = []
for g in PACK["glossary"]:
    cs = [cid for cid, tx in texts.items() if g["term_or"] in tx]
    glossary.append({"or": g["term_or"], "en": g["term_en"], "def": g.get("definition_or", ""), "c": cs[0] if cs else None})

qb = {}
for q in PACK["questions"]:
    if q["qtype"] != "mcq" or q.get("correct_option") is None:
        continue
    qb[q["question_id"]] = {
        "id": q["question_id"],
        "c": q["concept_id"],
        "d": DIFF.get(q.get("difficulty"), 1),
        "s": q["prompt_or"],
        "o": q["options"],
        "a": q["correct_option"],
        "f": q.get("explanation_or") or "",
        "tag": q.get("misconception_tag"),
    }

chunks_js = [{"id": k["chunk_id"], "c": k["concept_id"], "text": k["text_or"]} for k in PACK["chunks"]]
chapters_js = [{"id": ch["chapter_id"], "t": {"en": ch.get("title_en", ""), "or": ch.get("title_or", "")}} for ch in PACK["chapters"]]

def j(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))

js = f"""/* GENERATED by scripts/export_curriculum.py — do not edit by hand.
   Source of truth: packs/{manifest['pack_id']}-{manifest['version']}.json (same ids the backend uses). */
export const PACK={{id:{j(manifest['pack_id'])},version:'{manifest['version']}',vnum:1,sizeMB:{manifest['byte_size']/1048576:.2f},bytes:{manifest['byte_size']},checksum:'{manifest['checksum_sha256']}',contentVersion:'{manifest['content_version']}'}};
export const CHAPTERS={j(chapters_js)};
export const CONCEPTS={j(concepts)};
export const QB={j(qb)};
export const GL={j(glossary)};
export const CHUNKS={j(chunks_js)};
"""
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes): {len(concepts)} concepts, {len(qb)} questions, {len(glossary)} glossary terms, {len(chunks_js)} chunks")
